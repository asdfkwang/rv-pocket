import { getLang } from "./i18n";

// Player-facing prose that lives in the views rather than in a chapter file.
// Machine-facing text — register names, addresses, code identifiers, and the panel
// labels that name hardware state — stays in English on purpose: the fiction is that
// you are reading a device, and the code you type is never translated.
export type UiText = { en: string; ko: string };

export function ui(text: UiText | string): string {
  if (typeof text === "string") return text;
  return getLang() === "ko" ? text.ko : text.en;
}

// {name} placeholders are filled with machine values, which stay untranslated.
export function fill(text: UiText, values: Record<string, string>): string {
  return ui(text).replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match);
}

